-- Particle emitter presets used by world plans (chimney smoke, Current motes,
-- falls mist, fireflies...). Plain numbers and palette keys only; WorldFX turns
-- a preset into a configured ParticleEmitter. Built-in rbxasset particle
-- textures keep the effects original and dependency-free.

export type Preset = {
	texture: string,
	rate: number,
	lifetime: { number },
	speed: { number },
	spread: { number },
	size: { { number } }, -- {time, value}
	transparency: { { number } },
	color: string, -- palette key
	colorEnd: string?,
	lightEmission: number,
	lightInfluence: number,
	acceleration: { number },
	drag: number,
	rotSpeed: { number },
	squash: number?,
	zOffset: number?,
	area: boolean, -- emits from a volume part when the placement has a size
	night: boolean?, -- only active at night
	quality: number, -- multiplier applied per EffectsQuality step
	direction: string?, -- EmissionDirection
}

